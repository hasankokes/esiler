import { NextRequest, NextResponse } from "next/server";
import { supabase } from "@/lib/supabase";
import catalog from "@/data/products.json";

export async function GET() {
    const { data: products, error } = await supabase
        .from("products")
        .select("*")
        .order("sort_order", { ascending: true })
        .order("id", { ascending: true });
    // Supabase erişilemezse veya boşsa Trendyol'dan oluşturulan kataloğu kullan
    if (error || !products?.length) {
        return NextResponse.json(catalog);
    }
    return NextResponse.json(products);
}

export async function PATCH(req: NextRequest) {
    const session = req.cookies.get("admin_session");
    if (session?.value !== "authenticated") {
        return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const body = await req.json();
    const { products } = body;

    if (!Array.isArray(products)) {
        return NextResponse.json({ error: "Invalid products data" }, { status: 400 });
    }

    // Update each product's sort_order
    const updates = products.map((p: { id: number; sort_order: number }) =>
        supabase.from("products").update({ sort_order: p.sort_order }).eq("id", p.id)
    );

    const results = await Promise.all(updates);
    const errors = results.filter((r) => r.error);

    if (errors.length > 0) {
        return NextResponse.json(
            { error: "Some updates failed", details: errors.map((e) => e.error?.message) },
            { status: 500 }
        );
    }

    return NextResponse.json({ success: true });
}

export async function POST(req: NextRequest) {
    const session = req.cookies.get("admin_session");
    if (session?.value !== "authenticated") {
        return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const body = await req.json();
    const newProduct = { ...body };
    // Auto-generate ID if needed, but supabase has generated by default identity for products.
    // If body contains an id manually set by UI, we could remove it to avoid conflict.
    if (newProduct.id) delete newProduct.id;

    const { data, error } = await supabase.from("products").insert([newProduct]).select().single();

    if (error) {
        return NextResponse.json({ error: error.message }, { status: 500 });
    }
    return NextResponse.json(data, { status: 201 });
}

export async function PUT(req: NextRequest) {
    const session = req.cookies.get("admin_session");
    if (session?.value !== "authenticated") {
        return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const body = await req.json();
    if (!body.id) {
        return NextResponse.json({ error: "ID required" }, { status: 400 });
    }

    const { data, error } = await supabase.from("products").update(body).eq("id", body.id).select().single();

    if (error) {
        return NextResponse.json({ error: error.message }, { status: 500 });
    }
    return NextResponse.json(data);
}

export async function DELETE(req: NextRequest) {
    const session = req.cookies.get("admin_session");
    if (session?.value !== "authenticated") {
        return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const { searchParams } = new URL(req.url);
    const id = Number(searchParams.get("id"));

    if (!id) {
        return NextResponse.json({ error: "ID required" }, { status: 400 });
    }

    const { error } = await supabase.from("products").delete().eq("id", id);

    if (error) {
        return NextResponse.json({ error: error.message }, { status: 500 });
    }
    return NextResponse.json({ success: true });
}
